#!/bin/bash
# UserPromptSubmit フック: 毎ターンの冒頭で最上位ルールをコンテキストに入れ直す。
#
# enforce-dialog.py が事後に差し戻す仕組みなのに対し、こちらは事前の予防。
# 会話が長くなって CLAUDE.md が後方に押しやられても、ルールが薄れないようにする。
#
# 注入するのは、忘れた時点で実害が出る 2 つ。
#   ルール1 (ダイアログ)   忘れると利用者が次に何を選べばいいか分からなくなる
#   ルール2-B (コスト提示) 忘れると知らないところで課金が積み上がる
set -uo pipefail

cat <<'RULE'
[最上位ルール1・例外なし] 利用者に選ばせるときは、本文に選択肢を書き並べず、必ず
AskUserQuestion ツールのダイアログで提示すること。「A と B のどちらにしますか？」と
文章で聞くのは禁止。二択・多択・方針の確認・PR を作るかどうか、すべてダイアログで出す。
推奨があれば先頭に置き、ラベルに「(推奨)」を付ける。

[最上位ルール2-B・例外なし] 反復作業（定期実行・自動化・これから毎日回すもの）を
提案・報告・変更するときは、API クレジットの消費量を必ず同じメッセージ内で示すこと。
聞かれてから答えるのでは遅い。1回あたり／1日あたり／1か月あたりの3つを揃える。
単価は記憶で答えず claude-api スキルの料金表から引く。実測と推定を区別し、推定なら
前提（モデル・入出力トークン数）を書く。量を増やす提案には増加後の月額を必ず併記する。
現在の実額は docs/recurring-job-costs.md にある。
RULE

exit 0
